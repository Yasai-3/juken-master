function createChoice(id, subCategory, difficulty, question, answer, wrongChoices, explanation) {
  // 選択肢の重複を排除し4つにする
  const optSet = new Set([answer]);
  for (const w of wrongChoices) {
    if (w !== answer && !optSet.has(w)) {
      optSet.add(w);
    }
    if (optSet.size === 4) break;
  }
  const options = Array.from(optSet);
  // 数値順または五十音順に並べ替え
  options.sort((a, b) => {
    const numA = parseFloat(a.replace(/[^0-9.-]/g, ''));
    const numB = parseFloat(b.replace(/[^0-9.-]/g, ''));
    if (!isNaN(numA) && !isNaN(numB)) return numA - numB;
    return a.localeCompare(b, 'ja');
  });

  return {
    id,
    subject: "算数",
    category: "文章題・特殊算",
    subCategory,
    difficulty,
    questionType: "choice",
    question,
    options,
    answer,
    acceptableAnswers: [answer],
    explanation
  };
}

