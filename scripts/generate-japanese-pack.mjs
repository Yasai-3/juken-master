function createChoice(id, subcategory, difficulty, question, answer, wrongChoices, explanation) {
  const options = [answer, ...wrongChoices.slice(0, 3)];
  // 決定論的ソート（選択肢順の固定）
  options.sort((a, b) => a.localeCompare(b, 'ja'));

  return {
    id,
    subject: "国語",
    category: "国語",
    subcategory,
    difficulty,
    questionType: "choice",
    question,
    options,
    answer,
    acceptableAnswers: [answer],
    explanation
  };
}

