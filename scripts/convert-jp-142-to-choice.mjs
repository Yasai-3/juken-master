// Shuffle function
function shuffleArray(arr) {
  const shuffled = [...arr];
  for (let i = shuffled.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
  }
  return shuffled;
}

// Convert questions in sampleQuiz
let convertedCount = 0;

sampleQuiz.forEach(q => {
  if (distractorMap[q.id]) {
    const dList = distractorMap[q.id];
    const correctAns = q.answer;

    // Build choices
    const allOptions = shuffleArray([correctAns, ...dList]);

    // Format new question text
    let newQ = q.question
      .replace(/について、.*という言葉を使って説明しなさい。?$/, 'として最も適切なものを1つ選びなさい。')
      .replace(/について、.*という語句を使って説明しなさい。?$/, 'として最も適切なものを1つ選びなさい。')
      .replace(/.*という言葉を使って説明しなさい。?$/, 'として最も適切なものを1つ選びなさい。')
      .replace(/.*という語句を使って説明しなさい。?$/, 'として最も適切なものを1つ選びなさい。')
      .replace(/説明しなさい。?$/, 'として最も適切なものを1つ選びなさい。');

    if (!newQ.includes('選びなさい')) {
      newQ = `${newQ}として最も適切なものを1つ選びなさい。`;
    }

    q.question = newQ;
    q.questionType = 'choice';
    q.options = allOptions;
    q.keywords = []; // No longer needed for choice
    convertedCount++;
  }
});

console.log(`Converted ${convertedCount} questions in sampleQuiz.json`);

